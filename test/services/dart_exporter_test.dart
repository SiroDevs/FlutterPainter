import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_painter/domain/models/drawing/drawing.dart';
import 'package:flutter_painter/domain/models/drawing/paint_layer.dart';
import 'package:flutter_painter/domain/models/editor/app_settings.dart';
import 'package:flutter_painter/domain/models/export/export_options.dart';
import 'package:flutter_painter/domain/models/shapes/shape.dart';
import 'package:flutter_painter/domain/models/shapes/shape_kind.dart';
import 'package:flutter_painter/domain/services/code_export/dart_exporter.dart';

const _rect = Shape(
  kind: ShapeKind.rect,
  points: [Offset(1, 2), Offset(30, 40)],
  fill: 0xFFFF0000,
  stroke: 0xFF000000,
);
const _tri = Shape(
  kind: ShapeKind.polygon,
  points: [Offset(0, 0), Offset(10, 0), Offset(5, 8)],
  fill: 0xFF00FF00,
);

Drawing _drawing({List<PaintLayer>? layers}) => Drawing(
  name: 'Rider',
  width: 100,
  height: 150,
  layers:
      layers ??
      const [
        PaintLayer(name: 'Body', shapes: [_rect, _tri]),
        PaintLayer(name: 'Wheels', shapes: [_tri]),
      ],
);

String _all(List files) => files.map((f) => f.content).join('\n');

void main() {
  group('DartExporter', () {
    test('refactored: painter + one file per layer under layers/', () {
      final files = DartExporter(_drawing()).generate();
      final paths = files.map((f) => f.path).toList();
      expect(paths, contains('rider_painter.dart'));
      expect(paths.where((p) => p.startsWith('layers/')).length,
          greaterThanOrEqualTo(2));
      expect(paths.every((p) => p.endsWith('.dart')), isTrue);
      expect(
        paths.every((p) => !p.startsWith('/') && !p.contains('..')),
        isTrue,
      );
    });

    test('monolithic: a single file', () {
      final files = DartExporter(
        _drawing(),
        options: const ExportOptions(style: CodeStyle.monolithic),
      ).generate();
      expect(files, hasLength(1));
      expect(files.single.content, contains('RiderPainter'));
    });

    test('output names the project and carries the design box', () {
      final text = _all(DartExporter(_drawing()).generate());
      expect(text, contains('GENERATED by Flutter Painter'));
      expect(text, contains('RiderPainter'));
      expect(text, contains('100'));
      expect(text, contains('150'));
    });

    test('is deterministic', () {
      final a = DartExporter(_drawing()).generate();
      final b = DartExporter(_drawing()).generate();
      expect(a, b);
    });

    test('calling generate twice on one exporter gives the same result', () {
      final e = DartExporter(_drawing());
      expect(e.generate(), e.generate());
    });

    test('layers without visible shapes are not exported', () {
      final d = _drawing(
        layers: [
          const PaintLayer(name: 'Body', shapes: [_rect]),
          const PaintLayer(name: 'Empty'),
          PaintLayer(name: 'Hidden', shapes: [_tri.copyWith(visible: false)]),
        ],
      );
      final text = _all(DartExporter(d).generate());
      expect(text, contains('Body'));
      expect(text, isNot(contains('Empty')));
      expect(text, isNot(contains('Hidden')));
    });

    test('duplicate layer names get unique classes', () {
      final d = _drawing(
        layers: const [
          PaintLayer(name: 'Wheel', shapes: [_rect]),
          PaintLayer(name: 'Wheel', shapes: [_tri]),
        ],
      );
      final files = DartExporter(d).generate();
      final paths = files.map((f) => f.path).toSet();
      expect(paths.length, files.length);
      expect(_all(files), contains('RiderWheel2Layer'));
    });

    test('colour formats are honoured', () {
      String gen(ColorFormat f) => _all(
        DartExporter(
          _drawing(),
          options: ExportOptions(colorFormat: f, colorConstants: false),
        ).generate(),
      );
      expect(gen(ColorFormat.hex), contains('0xFFFF0000'));
      expect(gen(ColorFormat.argb), contains('Color.fromARGB'));
      expect(gen(ColorFormat.rgbo), contains('Color.fromRGBO'));
    });

    test('colour constants option changes the output', () {
      String gen(bool c) => _all(
        DartExporter(
          _drawing(),
          options: ExportOptions(colorConstants: c),
        ).generate(),
      );
      expect(gen(true), isNot(gen(false)));
    });

    test('a drawing name with newlines cannot break out of a comment', () {
      final d = Drawing(
        name: 'Evil\nvoid main() {}',
        layers: const [PaintLayer(name: 'A', shapes: [_rect])],
      );
      final text = _all(DartExporter(d).generate());
      expect(text, isNot(contains('\nvoid main() {}')));
    });
  });
}
