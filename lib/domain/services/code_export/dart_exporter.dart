/// Exports a drawing as standalone Dart painter code.
class DartExporter extends _DartExporterBase
    with
        _DartExporterShapeWriter,
        _DartExporterGroupWriter,
        _DartExporterLayoutWriter {
  DartExporter(super.drawing, {super.options});

  List<ExportFile> generate() {
    _usedColors.clear();
    return options.style == CodeStyle.monolithic
        ? _monolithic()
        : _refactored();
  }
}

abstract class _DartExporterBase {
  _DartExporterBase(this.drawing, {this.options = const ExportOptions()});

  final Drawing drawing;
  final ExportOptions options;

  final Set<int> _usedColors = <int>{};
  bool _resetShader = false;

  late final List<int> _layerIndexes = [
    for (var index = 0; index < drawing.layers.length; index++)
      if (drawing.layers[index].shapes.any((shape) => shape.visible)) index,
  ];
  late final List<PaintLayer> _layers = [
    for (final index in _layerIndexes) drawing.layers[index],
  ];
  late final List<String> _names = _uniqueNames();
  late final String _root = pascalCase(drawing.name);

  String get _paintField => '''
  final Paint _paint = Paint()
    ..isAntiAlias = true
    ..strokeCap = StrokeCap.round
    ..strokeJoin = StrokeJoin.round;''';

  String get folderName => snakeCase(_root);
  String get _painterClass => '${_root}Painter';
  String get _painterFile => '${folderName}_painter.dart';
  String _layerFolder(int index) => 'layers/${snakeCase(_names[index])}';
  String _layerClass(int index) => '$_root${_names[index]}Layer';
  String _layerFile(int index) =>
      '${_layerFolder(index)}/${snakeCase(_names[index])}_layer.dart';
  List<_ShapeFunction> _shapeFunctions(PaintLayer layer);
  List<String> _layerMethod(String name, PaintLayer layer, int layerIndex);

  Map<String, int> get layerIndexByPath => {
    for (var index = 0; index < _layers.length; index++)
      _layerFile(index): _layerIndexes[index],
  };

  String _label() => _oneLine(drawing.name);
  String _oneLine(String value) => value.replaceAll(RegExp(r'[\r\n]+'), ' ');
  String _generatedLine() =>
      '// GENERATED by Flutter Painter from "${_label()}".';

  List<String> _header() => [
    _generatedLine(),
    '// Design box: ${fmt(drawing.width)} x ${fmt(drawing.height)} units. '
        'Static artwork: apply lean, bob or steering around each paint call.',
  ];

  List<String> _sizeConstants() => [
    '  static const double width = ${fmt(drawing.width)};',
    '  static const double height = ${fmt(drawing.height)};',
  ];

  List<String> _uniqueNames() {
    final seen = <String, int>{};
    return [
      for (final layer in _layers)
        () {
          final base = pascalCase(layer.name);
          final number = seen.update(
            base,
            (value) => value + 1,
            ifAbsent: () => 1,
          );
          return number > 1 ? '$base$number' : base;
        }(),
    ];
  }

  bool _hasGradient(PaintLayer layer);
  bool _usesPath(Shape shape);
  List<String> _shape(Shape shape, {required bool comment});
  String _colorName(int argb);
  String _colorLiteral(int argb);

  // ignore: unused_element
  List<_ExportGroup> get _groups;
  List<_ExportGroup> get _paintedGroups;
  List<_ExportGroup> _groupsInLayer(int layerIndex);
  _ExportGroup? _groupForShape(int layerIndex, Shape shape);
  String _groupField(_ExportGroup group);
  String _groupFile(_ExportGroup group);
  String _groupImport(_ExportGroup group);
  List<_ShapeFunction> _groupFunctions(_ExportGroup group);
  List<String> _groupClassLines(
    _ExportGroup group,
    List<_ShapeFunction> functions,
  );
  String _groupSource(_ExportGroup group);
}

class _ShapeFunction {
  const _ShapeFunction({
    required this.index,
    required this.name,
    required this.doc,
    required this.body,
    required this.usesPath,
  });

  final int index;
  final String name;
  final String? doc;
  final List<String> body;
  final bool usesPath;
}

class _ExportGroup {
  const _ExportGroup({
    required this.layerIndex,
    required this.id,
    required this.name,
    required this.className,
  });

  final int layerIndex;
  final String id;
  final String name;
  final String className;
}
